  /** 根据调研方式生成搜索关键词 & 必须包含的词 */
  function buildKeywords(mode, o, key) {
    const pk = get(key);
    const clean = s => String(s || '').trim();
    if (mode === 'brand') {
      const brands = String(o.brands || '').split(/[\n,，、]/).map(clean).filter(Boolean).slice(0, 6);
      const city = clean(o.city);
      return brands.map(b => ({ kw: city ? `${b} ${city}` : b, must: [[b]], group: b }));
    }
    if (mode === 'city') {
      const city = clean(o.city), area = clean(o.area), cat = clean(o.cat);
      if (!cat || !(city || area)) return [];
      const place = area ? (city ? [area, city] : [area]) : [city];
      const out = [];
      pk.city.slice(0, 3).forEach(sfx => out.push({ kw: `${place[0]}${cat}${sfx}`, must: [place, [cat]], group: '' }));
      if (area && city) out.push({ kw: `${city}${cat}推荐`, must: [place, [cat]], group: '' });
      return out;
    }
    if (mode === 'national') {
      const cat = clean(o.cat), pos = clean(o.pos);
      if (!cat) return [];
      return pk.national.slice(0, 3).map(sfx => ({ kw: `${pos}${cat}${sfx}`, must: [[cat]], group: '' }));
    }
    const kws = String(o.custom || '').split(/\n/).map(clean).filter(Boolean).slice(0, 8);
    const must = String(o.must || '').trim();
    return kws.map(k => ({ kw: k, must: must ? parseMust(must) : [], group: '' }));
  }
  /** "广州/天河 + 火锅" → [['广州','天河'],['火锅']]（+ 表示都要有，/ 表示有一个就行） */
  function parseMust(s) { return String(s || '').split(/\s*\+\s*/).map(g => g.split(/[\/|｜]/).map(x => x.trim()).filter(Boolean)).filter(g => g.length); }
  function mustText(must) { return (must || []).map(g => g.join('/')).join(' + '); }

